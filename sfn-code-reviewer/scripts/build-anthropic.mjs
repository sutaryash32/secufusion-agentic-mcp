#!/usr/bin/env node
// Builds the Claude Code plugin in engines/anthropic/ from the provider-neutral sources:
//   prompts/        -> agents/*.md and skills/review/SKILL.md
//   config/*.yml    -> skills/review/config/*.json
//   rules/          -> skills/review/rules/ (suppressions.yml -> .json)
//   schemas/        -> skills/review/schemas/
//   scripts/ (runtime subset) -> skills/review/bin/
// The output is committed so the plugin works straight from git. `--check` fails if it is stale.
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const PLUGIN_NAME = 'sfn';
const GENERATED = ['agents', 'skills/review/SKILL.md', 'skills/review/bin', 'skills/review/config', 'skills/review/rules', 'skills/review/schemas', '.claude-plugin/plugin.json'];

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const review = yaml.load(readFileSync(join(root, 'config/review.config.yml'), 'utf8'));
const repos = yaml.load(readFileSync(join(root, 'config/repos.yml'), 'utf8'));
const suppressions = yaml.load(readFileSync(join(root, 'rules/suppressions.yml'), 'utf8')) ?? { suppressions: [] };
validateConfig();

const outRoot = check ? mkdtempSync(join(tmpdir(), 'sfn-build-')) : join(root, 'engines/anthropic');
if (check) cpSync(join(root, 'engines/anthropic'), outRoot, { recursive: true });
for (const g of GENERATED) rmSync(join(outRoot, g), { recursive: true, force: true });

const skill = join(outRoot, 'skills/review');
const banner = (src) => `<!-- GENERATED by scripts/build-anthropic.mjs from ${src} — edit the source, then run \`npm run build\`. -->\n`;

// --- plugin manifest
write('.claude-plugin/plugin.json', JSON.stringify({
  name: PLUGIN_NAME,
  version: pkg.version,
  description: 'SecuFusion code reviewer: specialist reviewers (db, security, contracts) + adversarial verify for the sfn-* repos. /sfn:review',
  author: { name: 'SecuFusion platform team' },
}, null, 2) + '\n');

// --- orchestrator skill
{
  const { meta, body } = parsePrompt('prompts/orchestrator.md');
  write('skills/review/SKILL.md', frontmatter({ name: meta.name, description: meta.description, 'argument-hint': meta['argument-hint'] }) + banner('prompts/orchestrator.md') + body);
}

// --- specialist + verify agents
const shared = ['severity-guide.md', 'output-contract.md'].map((f) => readFileSync(join(root, 'prompts/shared', f), 'utf8')).join('\n');
const agentSources = [
  ...readdirSync(join(root, 'prompts/specialists')).filter((f) => f.endsWith('.md')).map((f) => [`prompts/specialists/${f}`, 'specialist']),
  ['prompts/verify.md', 'verify'],
];
for (const [src, kind] of agentSources) {
  const { meta, body } = parsePrompt(src);
  const fm = frontmatter({
    name: meta.name,
    description: meta.description,
    tools: 'Read, Grep, Glob, Bash',
    model: review.anthropic.models[kind],
  });
  write(`agents/${meta.name}.md`, fm + banner(src) + body + (kind === 'specialist' ? `\n${shared}` : ''));
}

// --- runtime bundle
write('skills/review/config/review.json', JSON.stringify(review, null, 2) + '\n');
write('skills/review/config/repos.json', JSON.stringify(repos, null, 2) + '\n');
copyDir('rules', 'skills/review/rules', (f) => !f.endsWith('.yml'));
write('skills/review/rules/suppressions.json', JSON.stringify(suppressions, null, 2) + '\n');
copyDir('schemas', 'skills/review/schemas');
// Self-contained copy for `claude -p --json-schema` (no external $ref).
{
  const finding = JSON.parse(readFileSync(join(root, 'schemas/finding.schema.json'), 'utf8'));
  const result = JSON.parse(readFileSync(join(root, 'schemas/review-result.schema.json'), 'utf8'));
  const { $schema, $id, ...findingBody } = finding;
  result.$defs = { finding: findingBody };
  result.properties.findings.items = { $ref: '#/$defs/finding' };
  delete result.$id;
  delete result.$schema; // the CLI's validator rejects the draft 2020-12 meta-schema URI
  write('skills/review/schemas/review-result.inlined.json', JSON.stringify(result, null, 2) + '\n');
}
for (const f of ['collect-scope.mjs', 'finalize.mjs', 'render-report.mjs', 'db-snapshot.mjs', 'dep-audit.mjs', 'post-ado-pr.mjs', 'create-ado-bugs.mjs', 'release-check.mjs', 'metrics.mjs', 'feedback.mjs', 'pr-description.mjs', 'pr-chat.mjs']) {
  write(`skills/review/bin/${f}`, readFileSync(join(root, 'scripts', f), 'utf8'));
}
copyDir('scripts/lib', 'skills/review/bin/lib');

if (check) {
  const stale = diffTrees(join(root, 'engines/anthropic'), outRoot);
  rmSync(outRoot, { recursive: true, force: true });
  if (stale.length) {
    console.error(`[build] engines/anthropic is stale — run \`npm run build\` and commit:\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  console.log('[build] engines/anthropic is up to date.');
} else {
  console.log(`[build] plugin "${PLUGIN_NAME}" ${pkg.version} written to ${relative(process.cwd(), outRoot) || '.'}`);
}

// ---------------------------------------------------------------------------
function parsePrompt(rel) {
  const text = readFileSync(join(root, rel), 'utf8');
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${rel}: missing frontmatter`);
  const meta = yaml.load(m[1]);
  for (const k of ['name', 'description']) if (!meta[k]) throw new Error(`${rel}: frontmatter needs "${k}"`);
  return { meta, body: m[2].replace(/^\n+/, '') };
}

function frontmatter(obj) {
  const clean = Object.fromEntries(Object.entries(obj).filter(([, v]) => v != null));
  return `---\n${yaml.dump(clean, { lineWidth: -1 }).trim()}\n---\n\n`;
}

function write(rel, content) {
  const file = join(outRoot, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}

function copyDir(srcRel, destRel, filter = () => true) {
  const src = join(root, srcRel);
  for (const name of readdirSync(src)) {
    const p = join(src, name);
    if (statSync(p).isDirectory()) copyDir(join(srcRel, name), join(destRel, name), filter);
    else if (filter(name)) write(join(destRel, name), readFileSync(p));
  }
}

function listFiles(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? listFiles(p, base) : [relative(base, p)];
  });
}

function diffTrees(a, b) {
  const files = new Set([...listFiles(a), ...listFiles(b)]);
  return [...files].filter((f) => {
    const pa = join(a, f);
    const pb = join(b, f);
    return !existsSync(pa) || !existsSync(pb) || !readFileSync(pa).equals(readFileSync(pb));
  }).sort();
}

function validateConfig() {
  const errs = [];
  if (!['anthropic', 'openai'].includes(review.engine)) errs.push(`review.config.yml: engine must be anthropic|openai`);
  for (const k of ['orchestrator', 'specialist', 'verify']) if (!review.anthropic?.models?.[k]) errs.push(`review.config.yml: anthropic.models.${k} missing`);
  if (!['blocker', 'major', 'minor', 'none'].includes(review.gate?.failOn)) errs.push('review.config.yml: gate.failOn invalid');
  for (const r of repos.riskRules ?? []) {
    try { new RegExp(r.match); } catch (e) { errs.push(`repos.yml: riskRules.${r.id}.match: ${e.message}`); }
  }
  for (const s of suppressions.suppressions ?? []) {
    if (!s.reason || !s.expires) errs.push(`suppressions.yml: every entry needs reason and expires (${JSON.stringify(s)})`);
    if (!s.id && !s.ruleId && !s.path) errs.push(`suppressions.yml: entry needs id, or ruleId/path (${JSON.stringify(s)})`);
  }
  if (errs.length) {
    console.error(errs.map((e) => `[build] ${e}`).join('\n'));
    process.exit(1);
  }
}

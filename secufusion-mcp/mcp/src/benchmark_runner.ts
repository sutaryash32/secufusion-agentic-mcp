import { investigateEntity, investigateRelationship } from "./investigation_engine.js";
import { 
    Requirement, loadRequirement, saveRequirement, 
    validateStateTransition, generateConfirmedSpecification 
} from "./requirement_manager.js";
import fs from 'fs';
import path from 'path';

const ecosystemRoot = "c:\\Users\\Yash\\Desktop\\mcp";

function getGraph() {
    const dnaPath = path.join(ecosystemRoot, ".secufusion", "dna.json");
    return JSON.parse(fs.readFileSync(dnaPath, "utf-8")).graph;
}

function runRetentionBenchmark() {
    console.log("=== RUNNING RETENTION BENCHMARK ===");
    const reqId = "BM-RET-1";
    let req: Requirement = {
        id: reqId,
        title: "Retention Policy Setup",
        status: "RAW",
        clarification_questions: [],
        raw_request: "The feature is available only to Master MSSP/MSSP users. Any tenant can configure retention. After span, events are cleaned using dynamic scheduling."
    };
    saveRequirement(ecosystemRoot, req);
    req.status = "UNDERSTOOD";
    
    // 1. Investigation Phase
    req.status = "INVESTIGATING";
    const graph = getGraph();
    
    const retRes = investigateEntity(graph, "Retention");
    const tenantRes = investigateEntity(graph, "Tenant");
    const eventRes = investigateEntity(graph, "Event");
    const relRes = investigateRelationship(graph, "Retention", "Event");

    req.facts = [
        retRes.summary,
        tenantRes.summary,
        eventRes.summary,
        relRes.summary
    ];
    
    // 2. Unknown / Conflict Detection
    req.unknowns = [
        "Which timestamp governs retention on Event?",
        "Are all event types covered?",
        "What happens when retention changes?",
        "Is deletion hard delete, soft delete?",
        "What authorization applies to parent/child access?"
    ];
    req.blockers = ["Missing explicit deletion semantics", "Missing authorization logic"];
    saveRequirement(ecosystemRoot, req);

    // 3. Clarification Required
    req.status = "CLARIFICATION_REQUIRED";
    req.clarification_questions.push({
        id: "CQ-RET-1",
        topic: "Deletion Semantics",
        issue: "Deletion is destructive and type is unknown.",
        state: "OPEN",
        severity: "CRITICAL",
        blocking: true,
        question: "Is the cleanup a hard delete or soft delete? Which timestamp governs it?",
        evidence: retRes.evidence,
        created_at: new Date().toISOString()
    });
    saveRequirement(ecosystemRoot, req);

    // 4. Resolve and Confirm
    req.clarification_questions[0].state = "RESOLVED";
    req.clarification_questions[0].answer = "Hard delete governed by created_at.";
    req.clarification_questions[0].decision = "Retention cleanup will hard delete based on created_at.";
    req.decisions = [req.clarification_questions[0].decision];
    req.blockers = [];
    
    req.status = "CONFIRMED";
    req.tenancy = "Parent reads/writes child policy";
    req.authorization = "Master MSSP only";
    req.data_lifecycle = "Hard delete after N days based on created_at";
    saveRequirement(ecosystemRoot, req);
    
    console.log(generateConfirmedSpecification(req));
}

function runUserDeletionBenchmark() {
    console.log("=== RUNNING USER DELETION BENCHMARK ===");
    const reqId = "BM-DEL-1";
    let req: Requirement = {
        id: reqId,
        title: "User Deletion",
        status: "RAW",
        clarification_questions: [],
        raw_request: "End-to-end functionality for deleting a selected user from the UI across all services."
    };
    saveRequirement(ecosystemRoot, req);
    req.status = "UNDERSTOOD";
    
    req.status = "INVESTIGATING";
    const graph = getGraph();
    
    const userRes = investigateEntity(graph, "User");
    const eventRes = investigateEntity(graph, "Event");
    const userEventRel = investigateRelationship(graph, "User", "Event");

    req.facts = [
        userRes.summary,
        userEventRel.summary
    ];
    
    req.unknowns = [
        "What happens to events generated by the user?",
        "Are there audit records that must be retained?"
    ];
    req.blockers = ["Unspecified retention of related audit events"];
    saveRequirement(ecosystemRoot, req);

    req.status = "CLARIFICATION_REQUIRED";
    req.clarification_questions.push({
        id: "CQ-DEL-1",
        topic: "Orphan Data",
        issue: "Events associated with the user exist.",
        state: "OPEN",
        severity: "CRITICAL",
        blocking: true,
        question: "Should events created by the user be deleted, anonymized, or retained?",
        evidence: userEventRel.evidence,
        created_at: new Date().toISOString()
    });
    saveRequirement(ecosystemRoot, req);

    req.clarification_questions[0].state = "RESOLVED";
    req.clarification_questions[0].answer = "Anonymize events, retain audit records.";
    req.clarification_questions[0].decision = "Events will be anonymized instead of deleted.";
    req.decisions = [req.clarification_questions[0].decision];
    req.blockers = [];
    
    req.status = "CONFIRMED";
    req.data_lifecycle = "Hard delete user metadata, anonymize associated events, retain audit records.";
    saveRequirement(ecosystemRoot, req);
    
    console.log(generateConfirmedSpecification(req));
}

try {
    runRetentionBenchmark();
    console.log("\\n");
    runUserDeletionBenchmark();
} catch(e) {
    console.error("Benchmark failed:", e);
    process.exit(1);
}
